#!/usr/bin/env python3
"""Writes Support/Localization/<language>.lproj/Localizable.strings from translations.py.

Usage: python3 scripts/localization/generate.py
"""
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
from translations import T  # noqa: E402

ROOT = os.path.join(os.path.dirname(__file__), "..", "..", "Support", "Localization")
LANGUAGES = {"en": None, "uk": 0, "cs": 1, "ru": 2}


def quote(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def main() -> None:
    for code, column in LANGUAGES.items():
        folder = os.path.join(ROOT, f"{code}.lproj")
        os.makedirs(folder, exist_ok=True)
        lines = ["/* Generated by scripts/localization/generate.py from translations.py. Don't edit by hand. */", ""]
        for key in sorted(T):
            value = key if column is None else T[key][column]
            if value.count("%") != key.count("%"):
                sys.exit(f"{code}: placeholders differ for {key!r}")
            lines.append(f"{quote(key)} = {quote(value)};")
        with open(os.path.join(folder, "Localizable.strings"), "w", encoding="utf-8") as file:
            file.write("\n".join(lines) + "\n")
        print(f"{code}: {len(T)} strings")


if __name__ == "__main__":
    main()
