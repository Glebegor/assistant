import AppKit
import Observation
import UniformTypeIdentifiers

/// Everything on the Shelf, plus the watchers that add screenshots and clipboard entries.
@Observable
@MainActor
final class ShelfStore {
    /// Newest first.
    private(set) var items: [ShelfItem]

    @ObservationIgnored private let screenshotWatcher = ScreenshotWatcher()
    @ObservationIgnored private let clipboardWatcher = ClipboardWatcher()

    /// Pasteboard types that password managers and similar apps use to say "don't record this".
    private static let privatePasteboardTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]
    private static let maxTextLength = 100_000

    init() {
        ShelfSettings.registerDefaults()
        items = ShelfPersistence.load()

        screenshotWatcher.onScreenshot = { [weak self] url in self?.addFile(url, source: .screenshot) }
        clipboardWatcher.onChange = { [weak self] pasteboard in self?.addFromPasteboard(pasteboard) }
        applySettings()

        NotificationCenter.default.addObserver(
            forName: UserDefaults.didChangeNotification, object: nil, queue: .main
        ) { [weak self] _ in
            MainActor.assumeIsolated { self?.applySettings() }
        }
    }

    // MARK: Adding

    func addFile(_ url: URL, source: ShelfItem.Source) {
        insert(ShelfItem(content: .file(path: url.path, bookmark: try? url.bookmarkData()), source: source))
    }

    func addText(_ text: String, source: ShelfItem.Source) {
        guard !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty,
              text.count <= Self.maxTextLength
        else { return }
        insert(ShelfItem(content: .text(text), source: source))
    }

    /// Handles files or text dropped onto the notch panel. Returns false if nothing was usable.
    func addDropped(_ providers: [NSItemProvider]) -> Bool {
        var accepted = false
        for provider in providers {
            if provider.hasItemConformingToTypeIdentifier(UTType.fileURL.identifier) {
                accepted = true
                _ = provider.loadObject(ofClass: URL.self) { url, _ in
                    guard let url else { return }
                    Task { @MainActor [weak self] in self?.addFile(url, source: .dropped) }
                }
            } else if provider.canLoadObject(ofClass: String.self) {
                accepted = true
                _ = provider.loadObject(ofClass: String.self) { text, _ in
                    guard let text else { return }
                    Task { @MainActor [weak self] in self?.addText(text, source: .dropped) }
                }
            }
        }
        return accepted
    }

    private func addFromPasteboard(_ pasteboard: NSPasteboard) {
        let types = pasteboard.types ?? []
        guard !types.contains(where: { Self.privatePasteboardTypes.contains($0.rawValue) }) else { return }

        // Files copied in Finder
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self],
                                             options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            urls.forEach { addFile($0, source: .clipboard) }
        } else if let text = pasteboard.string(forType: .string) {
            addText(text, source: .clipboard)
        } else if let png = Self.pngData(from: pasteboard) {
            let fileName = "\(UUID().uuidString).png"
            let url = ShelfPersistence.imagesDirectory.appending(path: fileName)
            guard (try? png.write(to: url)) != nil else { return }
            insert(ShelfItem(content: .image(fileName: fileName), source: .clipboard))
        }
    }

    private static func pngData(from pasteboard: NSPasteboard) -> Data? {
        if let png = pasteboard.data(forType: .png) { return png }
        guard let tiff = pasteboard.data(forType: .tiff) else { return nil }
        return NSBitmapImageRep(data: tiff)?.representation(using: .png, properties: [:])
    }

    private func insert(_ item: ShelfItem) {
        if let key = item.duplicateKey {
            items.removeAll { $0.duplicateKey == key }
        }
        items.insert(item, at: 0)

        // Keep only the newest clipboard entries.
        let clipboardItems = items.filter { $0.source == .clipboard }
        for old in clipboardItems.dropFirst(ShelfSettings.maxClipboardItems) {
            ShelfPersistence.deleteStoredFile(of: old)
            items.removeAll { $0.id == old.id }
        }
        save()
    }

    // MARK: Actions

    func remove(_ item: ShelfItem) {
        ShelfPersistence.deleteStoredFile(of: item)
        items.removeAll { $0.id == item.id }
        save()
    }

    func clear() {
        items.forEach(ShelfPersistence.deleteStoredFile)
        items.removeAll()
        save()
    }

    func copyToClipboard(_ item: ShelfItem) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        switch item.content {
        case .text(let text):
            pasteboard.setString(text, forType: .string)
        case .file:
            if let url = item.fileURL { pasteboard.writeObjects([url as NSURL]) }
        case .image:
            if let url = item.fileURL, let image = NSImage(contentsOf: url) { pasteboard.writeObjects([image]) }
        }
        clipboardWatcher.ignoreCurrentContents()
    }

    func open(_ item: ShelfItem) {
        guard let url = item.fileURL else { return }
        NSWorkspace.shared.open(url)
    }

    func revealInFinder(_ item: ShelfItem) {
        guard let url = item.fileURL else { return }
        NSWorkspace.shared.activateFileViewerSelecting([url])
    }

    /// What is handed to other apps when an item is dragged out of the Shelf.
    func dragProvider(for item: ShelfItem) -> NSItemProvider {
        switch item.content {
        case .text(let text):
            NSItemProvider(object: text as NSString)
        case .file, .image:
            item.fileURL.flatMap { NSItemProvider(contentsOf: $0) } ?? NSItemProvider()
        }
    }

    // MARK: Private

    private func applySettings() {
        screenshotWatcher.setEnabled(ShelfSettings.captureScreenshots)
        clipboardWatcher.setEnabled(ShelfSettings.clipboardHistory)
    }

    private func save() {
        ShelfPersistence.save(items)
    }
}
