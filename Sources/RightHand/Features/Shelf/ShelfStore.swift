import AppKit
import Observation
import UniformTypeIdentifiers

extension UTType {
    /// A Shelf item dragged inside RightHand (e.g. onto a folder). Declared in Info.plist.
    static let shelfItem = UTType(exportedAs: "com.hlibarseniuk.RightHand.shelf-item")
}

/// Everything on the Shelf, plus the watchers that add screenshots and clipboard entries.
@Observable
@MainActor
final class ShelfStore {
    /// Newest first.
    private(set) var items: [ShelfItem]
    /// Newest first.
    private(set) var folders: [ShelfFolder]
    /// Folder currently shown in the Shelf tab; nil = top level.
    var openFolderID: UUID?
    /// macOS doesn't let RightHand read the screenshots folder (needs permission).
    private(set) var needsScreenshotFolderAccess = false

    /// What can be dropped onto the panel or a folder.
    static let dropTypes: [UTType] = [.shelfItem, .fileURL, .image, .plainText]

    @ObservationIgnored private let screenshotWatcher = ScreenshotWatcher()
    @ObservationIgnored private let clipboardWatcher = ClipboardWatcher()

    /// Pasteboard types that password managers and similar apps use to say "don't record this".
    private static let privatePasteboardTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]
    private static let maxTextLength = 100_000

    init() {
        ShelfSettings.registerDefaults()
        let data = ShelfPersistence.load()
        items = data.items
        folders = data.folders

        screenshotWatcher.onScreenshot = { [weak self] url in self?.addFile(url, source: .screenshot) }
        screenshotWatcher.onAccessChange = { [weak self] allowed in
            if self?.needsScreenshotFolderAccess != !allowed { self?.needsScreenshotFolderAccess = !allowed }
        }
        clipboardWatcher.onChange = { [weak self] pasteboard in self?.addFromPasteboard(pasteboard) }
        applySettings()

        NotificationCenter.default.addObserver(
            forName: UserDefaults.didChangeNotification, object: nil, queue: .main
        ) { [weak self] _ in
            MainActor.assumeIsolated { self?.applySettings() }
        }
    }

    var openFolder: ShelfFolder? { folders.first { $0.id == openFolderID } }

    func items(in folderID: UUID?) -> [ShelfItem] {
        items.filter { $0.folderID == folderID }
    }

    // MARK: Adding

    /// Dropped files and screenshots are copied into the Shelf files folder.
    /// Files copied in Finder (clipboard) are only linked, so the clipboard doesn't duplicate files.
    func addFile(_ url: URL, source: ShelfItem.Source, folderID: UUID? = nil) {
        // Already ours (e.g. dragged out of the Shelf and back in): just move it.
        if let existing = items.first(where: { $0.fileURL?.standardizedFileURL == url.standardizedFileURL }) {
            move(itemID: existing.id, to: folderID)
            return
        }
        let isShelfDirectory = ([nil] + folders).contains {
            ShelfFiles.directory(for: $0).standardizedFileURL == url.standardizedFileURL
        }
        guard !isShelfDirectory else { return }

        guard source != .clipboard, !ShelfFiles.isInsideRoot(url) else {
            insert(ShelfItem(content: .file(path: url.path, bookmark: try? url.bookmarkData()),
                             source: source, folderID: folderID))
            return
        }

        // Replace an older copy of the same file instead of making "name 2".
        removeDuplicates(of: "file:\(url.path)")
        let directory = ShelfFiles.directory(for: folders.first { $0.id == folderID })
        Task {
            // Copying can take a while for big files on another disk, so do it off the main thread.
            let copy = try? await Task.detached { try ShelfFiles.copy(url, into: directory) }.value
            let file = copy ?? url // if copying fails, keep a link to the original
            insert(ShelfItem(content: .file(path: file.path, bookmark: try? file.bookmarkData()),
                             source: source, folderID: folderID,
                             originalPath: copy == nil ? nil : url.path))
        }
    }

    func addText(_ text: String, source: ShelfItem.Source, folderID: UUID? = nil) {
        guard !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty,
              text.count <= Self.maxTextLength
        else { return }
        insert(ShelfItem(content: .text(text), source: source, folderID: folderID))
    }

    /// Handles Shelf items, files or text dropped into `folderID` (nil = top level).
    /// Returns false if nothing was usable.
    func addDropped(_ providers: [NSItemProvider], into folderID: UUID?) -> Bool {
        var accepted = false
        for provider in providers {
            if provider.hasItemConformingToTypeIdentifier(UTType.shelfItem.identifier) {
                accepted = true
                _ = provider.loadDataRepresentation(forTypeIdentifier: UTType.shelfItem.identifier) { data, _ in
                    guard let data, let id = UUID(uuidString: String(decoding: data, as: UTF8.self)) else { return }
                    Task { @MainActor [weak self] in self?.move(itemID: id, to: folderID) }
                }
            } else if provider.hasItemConformingToTypeIdentifier(UTType.fileURL.identifier) {
                accepted = true
                _ = provider.loadObject(ofClass: URL.self) { url, _ in
                    guard let url else { return }
                    Task { @MainActor [weak self] in self?.addFile(url, source: .dropped, folderID: folderID) }
                }
            } else if provider.hasItemConformingToTypeIdentifier(UTType.image.identifier) {
                // Images without a file, e.g. the floating screenshot preview or a browser image.
                accepted = true
                let directory = directoryURL(for: folderID)
                _ = provider.loadFileRepresentation(forTypeIdentifier: UTType.image.identifier) { url, _ in
                    // The file only exists during this callback, so copy it into the Shelf right away.
                    guard let url, let copy = try? ShelfFiles.copy(url, into: directory) else { return }
                    Task { @MainActor [weak self] in self?.addReceivedFile(copy, folderID: folderID) }
                }
            } else if provider.canLoadObject(ofClass: String.self) {
                accepted = true
                _ = provider.loadObject(ofClass: String.self) { text, _ in
                    guard let text else { return }
                    Task { @MainActor [weak self] in self?.addText(text, source: .dropped, folderID: folderID) }
                }
            }
        }
        return accepted
    }

    /// A file that is already in the Shelf files folder (received from a drop).
    private func addReceivedFile(_ url: URL, folderID: UUID?) {
        insert(ShelfItem(content: .file(path: url.path, bookmark: try? url.bookmarkData()),
                         source: .dropped, folderID: folderID, originalPath: url.path))
    }

    private func addFromPasteboard(_ pasteboard: NSPasteboard) {
        let types = pasteboard.types ?? []
        guard !types.contains(where: { Self.privatePasteboardTypes.contains($0.rawValue) }) else { return }

        // Files copied in Finder
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self],
                                             options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            urls.forEach { addFile($0, source: .clipboard) }
        } else if let text = pasteboard.string(forType: .string) {
            addText(text, source: .clipboard)
        } else if let png = Self.pngData(from: pasteboard) {
            let fileName = "\(UUID().uuidString).png"
            let url = ShelfPersistence.imagesDirectory.appending(path: fileName)
            guard (try? png.write(to: url)) != nil else { return }
            insert(ShelfItem(content: .image(fileName: fileName), source: .clipboard))
        }
    }

    private static func pngData(from pasteboard: NSPasteboard) -> Data? {
        if let png = pasteboard.data(forType: .png) { return png }
        guard let tiff = pasteboard.data(forType: .tiff) else { return nil }
        return NSBitmapImageRep(data: tiff)?.representation(using: .png, properties: [:])
    }

    private func insert(_ item: ShelfItem) {
        if let key = item.duplicateKey { removeDuplicates(of: key) }
        items.insert(item, at: 0)

        // Keep only the newest clipboard entries.
        let clipboardItems = items.filter { $0.source == .clipboard }
        for old in clipboardItems.dropFirst(ShelfSettings.maxClipboardItems) {
            ShelfPersistence.deleteStoredFile(of: old)
            items.removeAll { $0.id == old.id }
        }
        save()
    }

    private func removeDuplicates(of key: String) {
        for duplicate in items where duplicate.duplicateKey == key {
            ShelfPersistence.deleteStoredFile(of: duplicate)
        }
        items.removeAll { $0.duplicateKey == key }
    }

    // MARK: Folders

    @discardableResult
    func createFolder() -> ShelfFolder {
        let folder = ShelfFolder(name: uniqueFolderName("New Folder"))
        folders.insert(folder, at: 0)
        try? FileManager.default.createDirectory(at: ShelfFiles.directory(for: folder), withIntermediateDirectories: true)
        save()
        return folder
    }

    /// Renames the folder and its folder on disk.
    func rename(_ folder: ShelfFolder, to name: String) {
        let trimmed = name.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.isEmpty, trimmed != folder.name,
              let index = folders.firstIndex(where: { $0.id == folder.id })
        else { return }

        let oldDirectory = ShelfFiles.directory(for: folders[index])
        folders[index].name = uniqueFolderName(trimmed, excluding: folder.id)
        let newDirectory = ShelfFiles.directory(for: folders[index])

        if FileManager.default.fileExists(atPath: oldDirectory.path),
           (try? FileManager.default.moveItem(at: oldDirectory, to: newDirectory)) != nil {
            // Point the copies inside at their new location.
            let oldPrefix = oldDirectory.standardizedFileURL.path + "/"
            let newPrefix = newDirectory.standardizedFileURL.path + "/"
            for i in items.indices {
                guard case .file(let path, _) = items[i].content, path.hasPrefix(oldPrefix) else { continue }
                let newPath = newPrefix + path.dropFirst(oldPrefix.count)
                items[i].content = .file(path: newPath, bookmark: try? URL(filePath: newPath).bookmarkData())
            }
        }
        save()
    }

    /// Deletes the folder and its items; its folder on disk goes to the Trash.
    /// Linked originals elsewhere are not touched.
    func deleteFolder(_ folder: ShelfFolder) {
        items(in: folder.id).forEach(ShelfPersistence.deleteStoredFile)
        items.removeAll { $0.folderID == folder.id }
        folders.removeAll { $0.id == folder.id }
        ShelfFiles.trash(ShelfFiles.directory(for: folder))
        if openFolderID == folder.id { openFolderID = nil }
        save()
    }

    /// Moves an item into a folder (nil = top level); copies are moved on disk too.
    func move(itemID: UUID, to folderID: UUID?) {
        guard let index = items.firstIndex(where: { $0.id == itemID }),
              items[index].folderID != folderID
        else { return }
        if case .file = items[index].content, items[index].ownsFile, let url = items[index].fileURL {
            let directory = ShelfFiles.directory(for: folders.first { $0.id == folderID })
            if let moved = ShelfFiles.move(url, into: directory) {
                items[index].content = .file(path: moved.path, bookmark: try? moved.bookmarkData())
            }
        }
        items[index].folderID = folderID
        save()
    }

    func directoryURL(for folderID: UUID?) -> URL {
        ShelfFiles.directory(for: folders.first { $0.id == folderID })
    }

    /// Opens the folder on disk in Finder.
    func revealDirectory(for folderID: UUID?) {
        let url = directoryURL(for: folderID)
        try? FileManager.default.createDirectory(at: url, withIntermediateDirectories: true)
        NSWorkspace.shared.open(url)
    }

    /// Dragging a Shelf folder out hands over its real folder with all copied files.
    func dragProvider(for folder: ShelfFolder) -> NSItemProvider {
        let url = ShelfFiles.directory(for: folder)
        try? FileManager.default.createDirectory(at: url, withIntermediateDirectories: true)
        return NSItemProvider(contentsOf: url) ?? NSItemProvider()
    }

    private func uniqueFolderName(_ base: String, excluding id: UUID? = nil) -> String {
        let taken = Set(folders.filter { $0.id != id }.map { ShelfFiles.directoryName(for: $0.name).lowercased() })
        var name = base
        var number = 2
        while taken.contains(ShelfFiles.directoryName(for: name).lowercased()) {
            name = "\(base) \(number)"
            number += 1
        }
        return name
    }

    // MARK: Actions

    func remove(_ item: ShelfItem) {
        ShelfPersistence.deleteStoredFile(of: item)
        items.removeAll { $0.id == item.id }
        save()
    }

    /// Removes the clipboard history on the top level of the Shelf.
    func clearClipboard() {
        let history = items.filter { $0.source == .clipboard && $0.folderID == nil }
        history.forEach(ShelfPersistence.deleteStoredFile)
        let ids = Set(history.map(\.id))
        items.removeAll { ids.contains($0.id) }
        save()
    }

    /// Removes the items in `folderID`, or everything (folders too) when nil.
    /// Copies go to the Trash; linked originals are not touched.
    func clear(folderID: UUID?) {
        if let folderID {
            items(in: folderID).forEach(ShelfPersistence.deleteStoredFile)
            items.removeAll { $0.folderID == folderID }
        } else {
            items.forEach(ShelfPersistence.deleteStoredFile)
            folders.forEach { ShelfFiles.trash(ShelfFiles.directory(for: $0)) }
            items.removeAll()
            folders.removeAll()
        }
        save()
    }

    func copyToClipboard(_ item: ShelfItem) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        switch item.content {
        case .text(let text):
            pasteboard.setString(text, forType: .string)
        case .file:
            if let url = item.fileURL { pasteboard.writeObjects([url as NSURL]) }
        case .image:
            if let url = item.fileURL, let image = NSImage(contentsOf: url) { pasteboard.writeObjects([image]) }
        }
        clipboardWatcher.ignoreCurrentContents()
    }

    func open(_ item: ShelfItem) {
        guard let url = item.fileURL else { return }
        NSWorkspace.shared.open(url)
    }

    func revealInFinder(_ item: ShelfItem) {
        guard let url = item.fileURL else { return }
        NSWorkspace.shared.activateFileViewerSelecting([url])
    }

    /// What is handed over when an item is dragged: the file/text for other apps,
    /// plus the item's id so dropping it on a Shelf folder moves it there.
    func dragProvider(for item: ShelfItem) -> NSItemProvider {
        let provider: NSItemProvider = switch item.content {
        case .text(let text):
            NSItemProvider(object: text as NSString)
        case .file, .image:
            item.fileURL.flatMap { NSItemProvider(contentsOf: $0) } ?? NSItemProvider()
        }
        let id = Data(item.id.uuidString.utf8)
        provider.registerDataRepresentation(forTypeIdentifier: UTType.shelfItem.identifier,
                                            visibility: .ownProcess) { completion in
            completion(id, nil)
            return nil
        }
        return provider
    }

    // MARK: Private

    private func applySettings() {
        screenshotWatcher.setEnabled(ShelfSettings.captureScreenshots)
        clipboardWatcher.setEnabled(ShelfSettings.clipboardHistory)
    }

    private func save() {
        ShelfPersistence.save(ShelfData(items: items, folders: folders))
    }
}
